// gmat.js - writes a script that can be opened in NASA's GMAT (General Mission Analysis Tool).
// NOTE: generated automatically; always check it by running it in GMAT.
import { THRUSTER_ISP } from './data.js';
import { EARTH_R, G0, hohmannDeltaV } from './physics.js';

const km = (ms) => (ms / 1000).toFixed(4);

export function generateGmatScript(mission, summary) {
  const startSma = (EARTH_R + mission.startAltKm).toFixed(2);
  const isHohmann = mission.type === 'hohmann';
  const h = isHohmann ? hohmannDeltaV(mission.startAltKm, mission.altitudeKm) : null;

  const create = [
    'Create Spacecraft CubeSat;',
    'Create ChemicalTank MicroTank;',
    'Create ForceModel Prop_ForceModel;',
    'Create Propagator Prop;',
    'Create ImpulsiveBurn Burn1;',
    isHohmann ? 'Create ImpulsiveBurn Burn2;' : null,
    'Create ReportFile OrbitReport;',
    'Create OrbitView OrbitView1;',
  ].filter(Boolean).join('\n');

  const burn = (name, dvMs) => `GMAT ${name}.CoordinateSystem = Local;
GMAT ${name}.Origin = Earth;
GMAT ${name}.Axes = VNB;
GMAT ${name}.Element1 = ${km(dvMs)};
GMAT ${name}.Element2 = 0;
GMAT ${name}.Element3 = 0;
GMAT ${name}.DecrementMass = true;
GMAT ${name}.Tank = {MicroTank};
GMAT ${name}.Isp = ${THRUSTER_ISP};
GMAT ${name}.GravitationalAccel = ${G0};`;

  const burns = isHohmann
    ? `${burn('Burn1', h.dv1)}\n${burn('Burn2', h.dv2)}`
    : `${burn('Burn1', mission.requiredDeltaV)}   % not fired in this mission (reserve only)`;

  const sequence = isHohmann
    ? `BeginMissionSequence;
Maneuver Burn1(CubeSat);
Propagate Prop(CubeSat) {CubeSat.Apoapsis};
Maneuver Burn2(CubeSat);
Propagate Prop(CubeSat) {CubeSat.ElapsedSecs = 5400};`
    : `BeginMissionSequence;
% Delta-V reserve (${mission.requiredDeltaV} m/s) is kept for orbit trim and deorbit, so we only propagate.
Propagate Prop(CubeSat) {CubeSat.ElapsedSecs = 86400};`;

  return `%----------------------------------------
% GMAT script generated by AstroArchitect
% Mission: ${mission.scriptTitle}
% Dry mass ${summary.dryMass.toFixed(3)} kg, fuel ${summary.fuel.toFixed(3)} kg, Isp ${THRUSTER_ISP} s
% Student project: check results inside GMAT.
%----------------------------------------

${create}

GMAT CubeSat.DateFormat = UTCGregorian;
GMAT CubeSat.Epoch = '01 Jan 2026 12:00:00.000';
GMAT CubeSat.CoordinateSystem = EarthMJ2000Eq;
GMAT CubeSat.DisplayStateType = Keplerian;
GMAT CubeSat.SMA = ${startSma};
GMAT CubeSat.ECC = ${mission.ecc};
GMAT CubeSat.INC = 51.6;
GMAT CubeSat.RAAN = 0;
GMAT CubeSat.AOP = 0;
GMAT CubeSat.TA = 0;
GMAT CubeSat.DryMass = ${summary.dryMass.toFixed(3)};
GMAT CubeSat.Tanks = {MicroTank};

GMAT MicroTank.FuelMass = ${summary.fuel.toFixed(3)};

${burns}

GMAT Prop_ForceModel.CentralBody = Earth;
GMAT Prop_ForceModel.PrimaryBodies = {Earth};
GMAT Prop_ForceModel.GravityField.Earth.Degree = 4;
GMAT Prop_ForceModel.GravityField.Earth.Order = 4;

GMAT Prop.FM = Prop_ForceModel;

GMAT OrbitReport.Filename = 'AstroArchitect_report.txt';
GMAT OrbitReport.Add = {CubeSat.ElapsedSecs, CubeSat.Earth.SMA, CubeSat.Earth.Altitude, CubeSat.TotalMass};
GMAT OrbitReport.WriteHeaders = true;

GMAT OrbitView1.Add = {CubeSat, Earth};
GMAT OrbitView1.CoordinateSystem = EarthMJ2000Eq;

${sequence}
`;
}